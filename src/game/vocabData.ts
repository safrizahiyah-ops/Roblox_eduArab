export function stripHarakat(text: string): string {
  return text.replace(/[\u064B-\u065F\u0670]/g, '');
}

export function getZoneAtPosition(x: number, z: number): PlayerZoneStatus {
  if (x <= -10) return 'suq';
  if (x >= 10) return 'madrasah';
  if (z <= -10) return 'bayt';
  return 'central';
}

